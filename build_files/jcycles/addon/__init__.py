class JCYCLES_OT_refresh_devices(bpy.types.Operator):
    """Ask the JCycles render runtime which devices this computer has"""
    bl_idname = "jcycles.refresh_devices"
    bl_label = "Refresh Devices"

    def execute(self, context):
        _cycles_shim.refresh_devices_blocking()
        prefs = context.preferences.addons[__package__].preferences
        try:
            prefs.refresh_devices()
        except Exception:
            pass
        status = _cycles_shim.device_status()
        if status:
            self.report({'WARNING'}, status)
        return {'FINISHED'}


class JCYCLES_OT_test_runtime(bpy.types.Operator):
    """Start the JCycles render runtime once and report its version"""
    bl_idname = "jcycles.test_runtime"
    bl_label = "Test Render Runtime"

    def execute(self, context):
        try:
            reply = jcy_client.one_shot({"cmd": "info"}, timeout=300.0)
        except Exception as ex:
            self.report({'ERROR'}, "JCycles runtime failed: {:s}".format(str(ex).splitlines()[0]))
            return {'CANCELLED'}
        self.report({'INFO'}, "JCycles runtime OK: Blender {:s} ({:s})".format(
            reply.get("version_string", "?"), reply.get("build_hash", "?")))
        return {'FINISHED'}


def _draw_jcycles_preferences(self, context):
    layout = self.layout
    box = layout.box()
    info = jcy_runtime.build_info()
    fork = info.get("fork", {})
    col = box.column(align=True)
    col.label(text="Render runtime: Blender {:s} ({:s}, {:s})".format(
        fork.get("version_string", "?"), fork.get("build_hash", "?")[:12], fork.get("build_branch", "?")),
        icon='BLENDER')
    col.label(text="Platform: {:s}, runtimes in package: {:s}".format(
        jcy_runtime.platform_tag(), ", ".join(jcy_runtime.available_runtimes()) or "none"))
    status = _cycles_shim.device_status()
    if status:
        col.label(text=status, icon='INFO')
    row = box.row()
    row.operator("jcycles.refresh_devices", icon='FILE_REFRESH')
    row.operator("jcycles.test_runtime", icon='CHECKMARK')
    box.prop(self, "jcycles_echo_worker")


_extra_classes = (JCYCLES_OT_refresh_devices, JCYCLES_OT_test_runtime)


def _install_presets():
    """Copy the fork's Cycles presets (rewritten for JCycles) to the user preset directory."""
    import shutil
    source = os.path.join(jcy_runtime.ADDON_DIR, "presets", "jcycles")
    if not os.path.isdir(source):
        return
    try:
        target = bpy.utils.user_resource('SCRIPTS', path=os.path.join("presets", "jcycles"), create=True)
    except Exception:
        return
    for dirpath, _dirnames, filenames in os.walk(source):
        relative = os.path.relpath(dirpath, source)
        for name in filenames:
            destination_dir = os.path.join(target, relative)
            destination = os.path.join(destination_dir, name)
            if os.path.exists(destination):
                continue
            os.makedirs(destination_dir, exist_ok=True)
            shutil.copy2(os.path.join(dirpath, name), destination)


def _at_exit():
    jcy_client.stop_all()
    jcy_runtime.cleanup_session()


def register():
    import atexit
    from . import properties, ui, operators, presets, jcy_engine, jcy_nodes

    jcy_compat.harden(ui.classes)
    jcy_compat.harden(getattr(presets, "classes", ()))

    # Additions to the preferences of the fork's Cycles add-on.
    prefs_cls = properties.JCyclesPreferences
    prefs_cls.__annotations__["jcycles_echo_worker"] = bpy.props.BoolProperty(
        name="Print Render Process Output",
        description="Print everything the JCycles render process (the fork's Blender) prints to the "
                    "system console. A log file is always written to the session directory",
        default=False,
    )
    original_draw = prefs_cls.draw

    def draw(self, context):
        _draw_jcycles_preferences(self, context)
        original_draw(self, context)

    prefs_cls.draw = draw

    properties.register()
    ui.register()
    operators.register()
    presets.register()
    for cls in _extra_classes:
        bpy.utils.register_class(cls)
    jcy_engine.register()
    jcy_nodes.register()

    atexit.unregister(_at_exit)
    atexit.register(_at_exit)
    _install_presets()
    if not bpy.app.background:
        # Device list for the preferences; asked once, then cached per computer.
        _cycles_shim.prefetch_devices()


def unregister():
    from . import properties, ui, operators, presets, jcy_engine, jcy_nodes, jcy_viewport

    jcy_viewport.free_all()
    jcy_nodes.unregister()
    jcy_engine.unregister()
    for cls in reversed(_extra_classes):
        bpy.utils.unregister_class(cls)
    presets.unregister()
    operators.unregister()
    ui.unregister()
    properties.unregister()
    jcy_client.stop_all()
